import shutil
from playwright.sync_api import sync_playwright, expect
with sync_playwright() as p:
    b=p.chromium.launch(executable_path=shutil.which('chromium'),args=['--no-sandbox'])
    page=b.new_page(viewport={'width':1400,'height':950})
    page.goto('http://127.0.0.1:8000/FreeMindAgain.html')
    page.evaluate('localStorage.clear();model=new Mindmap.Model();render();fit();')
    card=page.locator('#details')
    expect(card).not_to_be_visible()
    page.locator('.node.root').click()
    expect(card).not_to_be_visible()
    page.keyboard.press('F3')
    expect(card).to_be_visible()
    icon=page.locator('.panel-icon').bounding_box()
    title=page.locator('#node-title').bounding_box()
    hide=page.locator('#hide-details').bounding_box()
    assert icon['x'] < title['x'] < hide['x']
    assert abs(icon['y']-title['y'])<10
    width=page.locator('#canvas').bounding_box()['width']
    page.locator('#hide-details').click()
    expect(card).not_to_be_visible()
    assert page.locator('#canvas').bounding_box()['width']>width
    page.locator('.node.root').click()
    expect(card).not_to_be_visible()
    page.locator('#show-details').click()
    expect(card).to_be_visible()
    page.locator('#canvas').click(position={'x':30,'y':200})
    expect(card).not_to_be_visible()
    page.locator('.node.root').click()
    expect(card).not_to_be_visible()
    page.locator('#show-details').click()
    expect(card).to_be_visible()
    # Panning alone must not dismiss the card.
    canvas=page.locator('#canvas').bounding_box()
    page.mouse.move(canvas['x']+30,canvas['y']+200)
    page.mouse.down();page.mouse.move(canvas['x']+70,canvas['y']+220);page.mouse.up()
    expect(card).to_be_visible()
    page.locator('#label').fill('Проверка карточки')
    page.locator('#apply-editor').click()
    page.locator('#hide-details').click()
    page.locator('.node.root').dblclick()
    expect(card).to_be_visible()
    expect(page.locator('#rename-dialog')).not_to_be_visible()
    expect(page.locator('#label')).to_have_value('Проверка карточки')
    page.set_viewport_size({'width':390,'height':844})
    page.locator('#hide-details').click()
    expect(card).not_to_be_visible()
    page.locator('.node.root').click()
    expect(card).not_to_be_visible()
    page.locator('#show-details').click()
    expect(card).to_be_visible()
    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
    page.locator('#hide-details').click()
    page.locator('#add').click()
    page.locator('#rename-label').fill('Лист')
    page.locator('#apply-rename').click()
    expect(card).not_to_be_visible()
    page.locator('#fit').click()
    page.locator('.node.root').dblclick()
    expect(card).not_to_be_visible()
    assert page.locator('.node').count()==1
    page.locator('.node.root').dblclick()
    assert page.locator('.node').count()==2
    page.locator('.node:not(.root)').dblclick()
    expect(card).to_be_visible()
    expect(page.locator('#node-title')).to_have_text('Лист')
    expect(page.locator('#rename-dialog')).not_to_be_visible()
    b.close()
print('PASS: compact header, hide button, background click, node reopen, pan, preserved edits, mobile')
